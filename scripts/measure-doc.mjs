#!/usr/bin/env node
// Keeps the measured section of docs/WHAT-FELTKIT-GIVES-YOU.md equal to `feltkit measure`'s summary.
//
//   npm run measure:doc             rewrite the section between the markers
//   npm run measure:doc -- --check  fail when it no longer matches the code (CI)
//
// The measuring is FeltKit's (`feltkit measure`, which also keeps measure.json); this only places its
// Markdown in the page.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const DOC = `${root}docs/WHAT-FELTKIT-GIVES-YOU.md`;
const START = "<!-- measure:start (generated by npm run measure:doc; do not edit) -->";
const END = "<!-- measure:end -->";

const summary = execFileSync(`${root}node_modules/.bin/feltkit`, ["measure"], { cwd: root, encoding: "utf8", env: { ...process.env, NO_COLOR: "1" } }).trim();
const doc = readFileSync(DOC, "utf8");
const a = doc.indexOf("<!-- measure:start");
const b = doc.indexOf(END);
if (a < 0 || b < a) throw new Error("docs/WHAT-FELTKIT-GIVES-YOU.md has no measure markers");
const next = `${doc.slice(0, a)}${START}\n${summary}\n${doc.slice(b)}`;
if (process.argv.includes("--check")) {
  if (next !== doc) {
    console.error("docs/WHAT-FELTKIT-GIVES-YOU.md is out of date with the code: run npm run measure:doc");
    process.exit(1);
  }
  console.log("docs/WHAT-FELTKIT-GIVES-YOU.md matches feltkit measure");
} else {
  writeFileSync(DOC, next);
  console.log("updated docs/WHAT-FELTKIT-GIVES-YOU.md");
}
